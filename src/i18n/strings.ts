export const STRINGS: Record<Locale, Strings> = { ar, fr, en };
export const LOCALES: { id: Locale; label: string; native: string }[] = [
  { id: 'ar', label: 'العربية', native: 'العربية' },
  { id: 'fr', label: 'Français', native: 'Français' },
  { id: 'en', label: 'English', native: 'English' },
];

export function tr(locale: Locale, key: keyof Strings, vars?: Record<string, string | number>): string {
  let s: string = STRINGS[locale][key] ?? STRINGS.ar[key] ?? String(key);
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  }
  return s;
}
